/**
 * Signed QR voucher tokens (FR-SEC-01). A voucher encodes the reservation id
 * and an expiry (epoch seconds) under an HMAC-SHA256 signature (key id is
 * stable P1 — only a single server secret key; key rotation arrives with
 * A-07's key-id scheme in P2, so the wire format is `v1`).
 *
 * Wire format: `v1.<reservationId>.<expUnix>.<hex(hmacSha256(secret, first 3)>)`
 * The server verifies signature and `exp` with a 120 s tolerance against the
 * scan's `occurredAt` (devices are up to a couple of minutes off; SRS 3.1).
 */
import { createHmac, timingSafeEqual } from "node:crypto";

const VERSION = "v1";
const TOLERANCE_SECONDS = 120;

function secret(): string {
  // Secrets live in env only (A-14): the renter QR is generated by the server.
  return process.env.VOUCHER_SECRET ?? process.env.BETTER_AUTH_SECRET ?? "dev-insecure-voucher-secret";
}

function hmacOf(prefix: string): string {
  return createHmac("sha256", secret()).update(prefix).digest("hex");
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

export function signVoucher(input: { reservationId: string; expiresAt: Date }): string {
  const exp = Math.floor(input.expiresAt.getTime() / 1000);
  const prefix = `${VERSION}.${input.reservationId}.${exp}`;
  return `${prefix}.${hmacOf(prefix)}`;
}

export type VoucherVerification =
  | { ok: true; reservationId: string }
  | { ok: false; code: "VOUCHER_INVALID" | "VOUCHER_EXPIRED" };

export function verifyVoucher(token: unknown, occurredAt: Date): VoucherVerification {
  if (typeof token !== "string") return { ok: false, code: "VOUCHER_INVALID" };
  const parts = token.split(".");
  if (parts.length !== 4 || parts[0] !== VERSION) return { ok: false, code: "VOUCHER_INVALID" };
  const reservationId = parts[1] ?? "";
  const expRaw = parts[2] ?? "";
  const sigRaw = parts[3] ?? "";
  if (!UUID_RE.test(reservationId) || !/^\d+$/.test(expRaw)) {
    return { ok: false, code: "VOUCHER_INVALID" };
  }
  const expectedHex = hmacOf(`${VERSION}.${reservationId}.${expRaw}`);
  const a = Buffer.from(sigRaw, "hex");
  const b = Buffer.from(expectedHex, "hex");
  if (a.length !== b.length || !timingSafeEqual(a, b)) {
    return { ok: false, code: "VOUCHER_INVALID" };
  }
  const expSec = Number(expRaw);
  if (occurredAt.getTime() / 1000 > expSec + TOLERANCE_SECONDS) {
    return { ok: false, code: "VOUCHER_EXPIRED" };
  }
  return { ok: true, reservationId };
}
